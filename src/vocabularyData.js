export const getAllWords = () => {
  const allWords = [];
  Object.entries(vocabularyData).forEach(([lecture, exercises]) => {
    Object.entries(exercises).forEach(([exercise, words]) => {
      words.forEach(wordObj => {
        allWords.push({
          ...wordObj,
          lecture,
          exercise,
          id: `${lecture}-${exercise}-${wordObj.word}`
        });
      });
    });
  });
  return allWords;
};
